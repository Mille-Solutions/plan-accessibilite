let current = 'fr';
try {
  const saved = localStorage.getItem('lang');
  if (saved && STRINGS[saved]) current = saved;
  else if (navigator.language && !navigator.language.startsWith('fr')) current = 'en';
} catch { /* stockage indisponible */ }

export const getLang = () => current;

export function setLang(lang) {
  current = STRINGS[lang] ? lang : 'fr';
  try { localStorage.setItem('lang', current); } catch { /* ignore */ }
  document.documentElement.lang = current;
  applyStatic();
}

export function t(key, vars = {}) {
  const s = STRINGS[current][key] ?? STRINGS.fr[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}

/** Texte localisé d'un objet {fr, en} ou d'une chaîne. */
export function loc(v) {
  if (!v) return '';
  if (typeof v === 'string') return v;
  return v[current] || v.fr || Object.values(v)[0];
}

export function applyStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder)); });
}
